model = get_chat_llm()

# Variant A: Plain Vector-Only RAG (only chunk similarity search, no Fact nodes, no calculator)
vector_only_agent = create_agent(
    model=model,
    tools=[search_chunks],
    system_prompt=(
        "You are a 10-K filings assistant with access only to `search_chunks` over 10-K text chunks.\n"
        "Search the 10-K chunks before answering. Cite `[chunk_id]` for any chunk used. Keep your answer brief (1-4 sentences)."
    ),
    name="vector_only",
)

# Variant B: Single Agent with All Tools (no multi-agent separation)
