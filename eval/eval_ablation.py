"""3-Variant Ablation & Latency Study for the SEC Filings Analyst.

Compares three architectures on the benchmark questions (`eval/eval_dataset.json`)
plus 5 multi-hop stress questions (risk category -> structured financial facts -> calculation):

  - Variant A (Vector-Only RAG): `create_agent` with ONLY `search_chunks` (no structured Fact nodes, no calculator)
  - Variant B (Single-Agent GraphRAG): `create_agent` with all 4 tools (`search_chunks`, `query_facts`, `query_companies_by_risk`, `calculator`)
  - Variant C (Multi-Agent GraphRAG): `supervisor` -> `researcher` -> `analyst` workflow

Measures per question and per category:
  - Retrieval Source Hit Rate % (`expected_sources` present in tool outputs)
  - Deterministic Numeric Accuracy % (1-decimal and 2-decimal match on numeric questions)
  - Wall-clock latency (median, p95, max seconds)
  - Token usage (input tokens, output tokens, and estimated USD cost on Claude Sonnet 5.5)

Saves full results incrementally to `eval/ablation_results.json`.
"""
